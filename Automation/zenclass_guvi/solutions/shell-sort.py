import sys

def shell_sort(arr):
    n = len(arr)
    gap = n // 2
    
    while gap > 0:
        for i in range(gap, n):
            temp = arr[i]
            j = i
            while j >= gap and arr[j - gap] > temp:
                arr[j] = arr[j - gap]
                j -= gap
            arr[j] = temp
        gap //= 2
    
    return arr

def main():
    data = sys.stdin.read().strip().split()
    if not data:
        return
    
    n = int(data[0])
    if n == 0:
        print()
        return
    
    arr = list(map(int, data[1:n+1]))
    sorted_arr = shell_sort(arr)
    print(' '.join(map(str, sorted_arr)))

if __name__ == "__main__":
    main()
